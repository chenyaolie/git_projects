CREATE DATABASE IF NOT EXISTS JavaEE DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE JavaEE;

-- 学生信息表
CREATE TABLE IF NOT EXISTS StudentDEMS (
    StudentId VARCHAR(20) PRIMARY KEY COMMENT '学号',
    StudentName VARCHAR(50) NOT NULL COMMENT '姓名',
    Department VARCHAR(100) NOT NULL COMMENT '院系',
    Password VARCHAR(100) NOT NULL COMMENT '密码（加密存储）',
    Balance DECIMAL(10,2) DEFAULT 0 COMMENT '餐费余额',
    IsLost TINYINT(1) DEFAULT 0 COMMENT '是否挂失（0-正常，1-挂失）',
    CreateTime DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UpdateTime DATETIME ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='学生信息表';

-- 食堂工作人员表
CREATE TABLE IF NOT EXISTS StaffDEMS (
    StaffId VARCHAR(20) PRIMARY KEY COMMENT '员工编号',
    StaffName VARCHAR(50) NOT NULL COMMENT '姓名',
    Password VARCHAR(100) NOT NULL COMMENT '密码（加密存储）',
    CreateTime DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UpdateTime DATETIME ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='食堂工作人员表';

-- 管理员表
CREATE TABLE IF NOT EXISTS AdminDEMS (
    AdminId VARCHAR(20) PRIMARY KEY COMMENT '管理员编号',
    AdminName VARCHAR(50) NOT NULL COMMENT '姓名',
    Password VARCHAR(100) NOT NULL COMMENT '密码（加密存储）',
    CreateTime DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UpdateTime DATETIME ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='管理员表';

-- 消费记录表
CREATE TABLE IF NOT EXISTS ConsumptionRecordDEMS (
    RecordId BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '记录ID',
    StudentId VARCHAR(20) NOT NULL COMMENT '学生学号',
    StaffId VARCHAR(20) NOT NULL COMMENT '操作员ID',
    Amount DECIMAL(10,2) NOT NULL COMMENT '消费金额',
    CreateTime DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '消费时间',
    FOREIGN KEY (StudentId) REFERENCES StudentDEMS(StudentId),
    FOREIGN KEY (StaffId) REFERENCES StaffDEMS(StaffId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='消费记录表';

-- 充值申请表
CREATE TABLE IF NOT EXISTS RechargeApplicationDEMS (
    ApplicationId BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '申请ID',
    StudentId VARCHAR(20) NOT NULL COMMENT '学生学号',
    Amount DECIMAL(10,2) NOT NULL COMMENT '充值金额',
    Status TINYINT(1) DEFAULT 0 COMMENT '状态（0-待审核，1-已通过，2-已拒绝）',
    AdminId VARCHAR(20) COMMENT '审核管理员ID',
    ApplyTime DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '申请时间',
    AuditTime DATETIME COMMENT '审核时间',
    FOREIGN KEY (StudentId) REFERENCES StudentDEMS(StudentId),
    FOREIGN KEY (AdminId) REFERENCES AdminDEMS(AdminId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='充值申请表';

-- 充值记录表
CREATE TABLE IF NOT EXISTS RechargeRecordDEMS (
    RecordId BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '记录ID',
    StudentId VARCHAR(20) NOT NULL COMMENT '学生学号',
    Amount DECIMAL(10,2) NOT NULL COMMENT '充值金额',
    Type TINYINT(1) NOT NULL COMMENT '充值类型（0-审核通过，1-管理员直接充值）',
    OperatorId VARCHAR(20) NOT NULL COMMENT '操作人ID',
    CreateTime DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '充值时间',
    FOREIGN KEY (StudentId) REFERENCES StudentDEMS(StudentId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='充值记录表';

